"""Можно ли вообще вытащить сцену из нисходящих, если не назначать ось заранее?

Что известно. На лобуле сцена представлена богато: потолок воспроизводимости
0.90, все четыре пары сцен различаются. На нисходящих по-нейронная картина не
воспроизводится вовсе (потолок 0.057), а назначенная заранее ось «средняя
левой популяции минус средняя правой» даёт сдвиги 0.01–0.39 Гц поверх
собственного перекоса в 9.92 Гц, и знаки не складываются в поворот.

Но ось была назначена, а не найдена. Популяция отбиралась стимуляцией ЦЕЛОГО
полушария, то есть под вопрос «какая сторона», и делится на левую и правую по
анатомии. Для маленького столба это может быть не та проекция.

Здесь ось ищется по данным. Половины пачки дают обучение и проверку: направление
строится по первой половине, а проверяется на второй, которой оно не видело.
Если и так не выходит — значит дело не в выборе оси, а в самом горлышке.

Контроль: то же самое на перемешанных метках сцен. Если разделение держится и
там, оно берётся из шума, а не из сцен.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from flypaths import out  # noqa: E402

PAIRS = [("слева 27°", "справа 27°"), ("впереди", "слева 27°"),
         ("два тонких", "один толстый"), ("выше горизонта", "ниже горизонта")]


def main():
    z = np.load(out("hybrid_vision_raw.npz"))
    keys = list(z.keys())
    scenes = sorted({k.split("|")[2] for k in keys})
    print("=" * 78)
    print(" ОСЬ ИЩЕТСЯ ПО ДАННЫМ, А НЕ НАЗНАЧАЕТСЯ")
    print("=" * 78)
    print(f"\nсцен: {len(scenes)}; всего массивов: {len(keys)}")

    for where, n_lab in (("dn", "нисходящие"), ("lc", "лобула")):
        print("\n" + "-" * 78)
        print(f" считывание: {n_lab}")
        print("-" * 78)
        print(f"  {'пара сцен':<34s} {'схема':<14s} {'разделение':>11s} "
              f"{'перемешано':>11s}")
        for scheme in ("гибрид", "старая схема"):
            for a, b in PAIRS:
                try:
                    a0 = z[f"{where}|{scheme}|{a}|0"]
                    a1 = z[f"{where}|{scheme}|{a}|1"]
                    b0 = z[f"{where}|{scheme}|{b}|0"]
                    b1 = z[f"{where}|{scheme}|{b}|1"]
                except KeyError:
                    continue
                # направление строим по ПЕРВЫМ половинам, проверяем на вторых
                w = a0 - b0
                nw = np.linalg.norm(w)
                if nw < 1e-12:
                    continue
                w = w / nw
                sep = float((a1 - b1) @ w)
                # масштаб шума: та же проекция на разность половин одной сцены
                noise = float(abs((a0 - a1) @ w) + abs((b0 - b1) @ w)) / 2
                rel = sep / max(noise, 1e-9)
                # контроль: направление из перемешанной пары половин
                w2 = a0 - b1
                w2 = w2 / max(np.linalg.norm(w2), 1e-12)
                sep2 = float((a1 - b0) @ w2)
                noise2 = float(abs((a0 - a1) @ w2) + abs((b0 - b1) @ w2)) / 2
                rel2 = sep2 / max(noise2, 1e-9)
                print(f"  {a + ' / ' + b:<34s} {scheme:<14s} "
                      f"{rel:>10.1f}σ {rel2:>10.1f}σ")

    print("\n" + "=" * 78)
    print(" КАК ЧИТАТЬ")
    print("=" * 78)
    print("  Разделение в единицах собственного шума. Направление строится на")
    print("  одной половине пачки и проверяется на другой, которой оно не")
    print("  видело, поэтому подгонки под шум тут быть не может.")
    print("  Столбец «перемешано» — то же самое, но половины перепутаны между")
    print("  сценами. Он показывает, сколько даёт устройство расчёта само по себе.")


if __name__ == "__main__":
    main()
